// Where a pin is, in a form that survives the page changing underneath it.
//
// A pin cannot be stored as a pair of coordinates: the next visit has a different
// viewport, different content above the fold, or a DOM rebuilt from scratch. Nor can
// it be stored as a CSS selector alone: pages like Routeloop's builder replace their
// markup with innerHTML on every edit, so `div:nth-of-type(3)` points at whatever
// happens to be third today.
//
// So an anchor records several independent descriptions of the element, strongest
// first, and re-finding it tries them in that order:
//
//   1. Stable attributes on the element or its ancestors (`data-bugzap-id`,
//      `data-testid`, a hand-written `id`). Exact when present, and the reason the
//      docs ask hosts to add `data-bugzap-id` to anything worth pinning.
//   2. A selector scoped from the nearest stable ancestor.
//   3. A fuzzy match on what the element looked like: tag, text, label, position
//      and size, scored here.
//   4. The original click point, drawn as an approximate pin, with the screenshot
//      as the fallback that always shows what was meant.
//
// This module is the pure half: the type, its validation, the generated-id filter,
// and the scorer. Gathering candidates from a live DOM is src/widget/anchor/.

export type Rect = { x: number; y: number; w: number; h: number }

/** A stable attribute found at capture. `depth` 0 is the element itself, 1 its parent. */
export type AnchorAttr = { depth: number; name: string; value: string }

export type Anchor = {
  v: 1
  attrs: AnchorAttr[]
  /** From the nearest stable ancestor (or body): `tag:nth-of-type(n)` steps. */
  selector: string
  tag: string
  /** Normalized text content, first TEXT_MAX chars. */
  text?: string
  /** aria-label, alt, title or name, whichever came first. */
  label?: string
  /** The element's box in document coordinates at capture. */
  rect: Rect
  /** The click as a fraction of the element's box, so the pin lands on the same
   *  spot of an element that has since changed size. */
  offset: { fx: number; fy: number }
  /** The click in document coordinates. The last resort. */
  page: { x: number; y: number }
  viewport: { w: number; h: number; dpr: number; sx: number; sy: number }
  /** Set when the click landed on an iframe the widget cannot see into, such as an
   *  embedded map. The pin anchors to the iframe element itself. */
  frame?: 'iframe'
}

export const ANCHOR_ATTRS_MAX = 8
export const TEXT_MAX = 80
const LABEL_MAX = 120
const SELECTOR_MAX = 512

/** Attributes treated as stable, strongest first. Hosts may add their own. */
export const DEFAULT_STABLE_ATTRS = ['data-bugzap-id', 'data-testid', 'data-test', 'data-cy', 'data-qa', 'id'] as const

/**
 * Whether an `id` was generated by a framework rather than written by a person, and
 * so will be different on the next render. Such an id is worse than none: it matches
 * nothing later and pushes a working fallback down the list.
 */
export function isGeneratedId(value: string): boolean {
  if (!value || value.length > 64) return true
  return (
    /:/.test(value) || // React useId (`:r1:`, `«r1»` is caught below)
    /[«»]/.test(value) ||
    /[0-9a-f]{8}-[0-9a-f]{4}-/i.test(value) || // UUID
    /[0-9a-f]{12,}/i.test(value) || // long hex run
    /\d{4,}/.test(value) || // a counter or timestamp
    /^ember\d+$/.test(value) ||
    /^(radix|headlessui|mui|react-select|downshift|rc)-/i.test(value)
  )
}

/** Whitespace collapsed and trimmed, cut to `max`. What text is compared as. */
export function normalizeText(raw: string, max = TEXT_MAX): string {
  return raw.replace(/\s+/g, ' ').trim().slice(0, max)
}

// --- Validation --------------------------------------------------------------

const finite = (v: unknown): v is number => typeof v === 'number' && Number.isFinite(v)
const clamp = (n: number, lo: number, hi: number) => Math.min(hi, Math.max(lo, n))
const obj = (v: unknown): Record<string, unknown> | null =>
  v && typeof v === 'object' && !Array.isArray(v) ? (v as Record<string, unknown>) : null

function readRect(v: unknown): Rect | null {
  const r = obj(v)
  if (!r || !finite(r.x) || !finite(r.y) || !finite(r.w) || !finite(r.h)) return null
  if (r.w < 0 || r.h < 0) return null
  return { x: r.x, y: r.y, w: r.w, h: r.h }
}

/**
 * An anchor from the wire, or null. Strict about structure, because a pin that
 * cannot be placed is worse than a report without one; lenient about lengths, which
 * are cut rather than refused.
 */
export function parseAnchor(raw: unknown): Anchor | null {
  const a = obj(raw)
  if (!a || a.v !== 1) return null
  if (typeof a.tag !== 'string' || !/^[a-z][a-z0-9-]{0,31}$/.test(a.tag)) return null
  if (typeof a.selector !== 'string' || a.selector.length > SELECTOR_MAX) return null

  const rect = readRect(a.rect)
  const off = obj(a.offset)
  const page = obj(a.page)
  const vp = obj(a.viewport)
  if (!rect || !off || !page || !vp) return null
  if (!finite(off.fx) || !finite(off.fy) || !finite(page.x) || !finite(page.y)) return null
  if (!finite(vp.w) || !finite(vp.h) || !finite(vp.dpr) || !finite(vp.sx) || !finite(vp.sy)) return null
  if (vp.w <= 0 || vp.h <= 0) return null

  const attrs: AnchorAttr[] = []
  if (Array.isArray(a.attrs)) {
    for (const item of a.attrs) {
      if (attrs.length >= ANCHOR_ATTRS_MAX) break
      const x = obj(item)
      if (!x || !finite(x.depth) || typeof x.name !== 'string' || typeof x.value !== 'string') continue
      if (!/^[a-z][a-z0-9_:-]{0,63}$/.test(x.name) || !x.value || x.value.length > 200) continue
      attrs.push({
        depth: clamp(Math.round(x.depth), 0, 32),
        name: x.name,
        value: x.value,
      })
    }
  }

  const text = typeof a.text === 'string' ? normalizeText(a.text) : ''
  const label = typeof a.label === 'string' ? normalizeText(a.label, LABEL_MAX) : ''
  return {
    v: 1,
    attrs,
    selector: a.selector,
    tag: a.tag,
    ...(text && { text }),
    ...(label && { label }),
    rect,
    offset: { fx: clamp(off.fx, 0, 1), fy: clamp(off.fy, 0, 1) },
    page: { x: page.x, y: page.y },
    viewport: {
      w: vp.w,
      h: vp.h,
      dpr: clamp(vp.dpr, 0.1, 10),
      sx: vp.sx,
      sy: vp.sy,
    },
    ...(a.frame === 'iframe' && { frame: 'iframe' as const }),
  }
}

// --- Fuzzy matching ----------------------------------------------------------

/** What the widget measures about each live element it considers. */
export type Candidate = {
  tag: string
  text?: string
  label?: string
  /** The element's own stable attributes, depth 0 only. */
  attrs: { name: string; value: string }[]
  rect: Rect
}

/** Below this, no candidate is trusted and the pin goes approximate. */
export const FUZZY_THRESHOLD = 0.6

const WEIGHTS = {
  text: 0.35,
  attrs: 0.2,
  label: 0.1,
  position: 0.2,
  size: 0.15,
}

function bigrams(s: string): Map<string, number> {
  const m = new Map<string, number>()
  const t = s.toLowerCase()
  for (let i = 0; i < t.length - 1; i++) {
    const g = t.slice(i, i + 2)
    m.set(g, (m.get(g) ?? 0) + 1)
  }
  return m
}

/** Sørensen–Dice over character bigrams: 1 for identical text, 0 for nothing shared.
 *  Tolerant of an edited word or a changed count, which is how a button's text
 *  usually differs between visits. */
export function textSimilarity(a: string, b: string): number {
  const x = a.toLowerCase().trim()
  const y = b.toLowerCase().trim()
  if (x === y) return 1
  if (x.length < 2 || y.length < 2) return 0
  const ga = bigrams(x)
  const gb = bigrams(y)
  let shared = 0
  for (const [g, n] of ga) shared += Math.min(n, gb.get(g) ?? 0)
  return (2 * shared) / (x.length - 1 + (y.length - 1))
}

/** Two optional strings compared; both absent is no evidence either way. */
function optionalSimilarity(a: string | undefined, b: string | undefined): number {
  if (!a && !b) return 0.5
  if (!a || !b) return 0
  return textSimilarity(a, b)
}

/**
 * How well a live element matches the anchor, 0 to 1.
 *
 * `scale` is the current viewport width over the captured one, applied to horizontal
 * positions and widths, because a fluid layout narrows horizontally while the
 * vertical order of the page stays put.
 */
export function scoreCandidate(anchor: Anchor, c: Candidate, scale = 1): number {
  if (c.tag !== anchor.tag) return 0

  const own = anchor.attrs.filter((x) => x.depth === 0)
  const attrs = own.length
    ? own.filter((x) => c.attrs.some((y) => y.name === x.name && y.value === x.value)).length / own.length
    : 0.5

  const ax = (anchor.rect.x + anchor.rect.w / 2) * scale
  const ay = anchor.rect.y + anchor.rect.h / 2
  const cx = c.rect.x + c.rect.w / 2
  const cy = c.rect.y + c.rect.h / 2
  const position = 1 / (1 + Math.hypot(cx - ax, cy - ay) / 200)

  const ratio = (p: number, q: number) => (p <= 0 && q <= 0 ? 1 : Math.min(p, q) / Math.max(p, q))
  const size = ratio(anchor.rect.w * scale, c.rect.w) * ratio(anchor.rect.h, c.rect.h)

  return (
    WEIGHTS.text * optionalSimilarity(anchor.text, c.text) +
    WEIGHTS.attrs * attrs +
    WEIGHTS.label * optionalSimilarity(anchor.label, c.label) +
    WEIGHTS.position * position +
    WEIGHTS.size * size
  )
}

/** The best candidate at or above FUZZY_THRESHOLD, or null. */
export function pickBest(anchor: Anchor, candidates: Candidate[], scale = 1): { index: number; score: number } | null {
  let best: { index: number; score: number } | null = null
  candidates.forEach((c, index) => {
    const score = scoreCandidate(anchor, c, scale)
    if (score >= FUZZY_THRESHOLD && (!best || score > best.score)) best = { index, score }
  })
  return best
}

/** Where on an element's current box the pin goes. */
export function pinPoint(rect: Rect, offset: Anchor['offset']): { x: number; y: number } {
  return { x: rect.x + offset.fx * rect.w, y: rect.y + offset.fy * rect.h }
}

/** The last resort: the original click, scaled horizontally to the current viewport. */
export function approximatePoint(anchor: Anchor, viewportWidth: number): { x: number; y: number } {
  return {
    x: anchor.page.x * (viewportWidth / anchor.viewport.w),
    y: anchor.page.y,
  }
}
